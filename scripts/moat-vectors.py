#!/usr/bin/env python3
"""Writes the MOAT test vectors the moat crate checks as JSON on stdout.

Usage: MOAT_DIR=<OpenScribbler/moat checkout> python3 scripts/moat-vectors.py

MOAT publishes its vectors only as the printed output of
reference/generate_test_vectors.py. This script imports that generator and
serializes what it returns, so every value, signatures included, comes from
MOAT's own code; nothing here signs or hashes. The generator is stdlib-only
and deterministic, so the output is byte-identical on every run and OS.

The Attestation Payload vector lives only in moat-spec.md, so it is read
from the spec's table and cross-checked against the generator's payload
function.

CI regenerates the file and fails when it differs from the committed
crates/moat/tests/vectors/moat-vectors.json.
"""

import hashlib
import json
import os
import pathlib
import re
import subprocess
import sys

moat_dir = os.environ.get("MOAT_DIR")
if not moat_dir:
    sys.exit("set MOAT_DIR to an OpenScribbler/moat checkout")
moat = pathlib.Path(moat_dir).resolve()
sys.path.insert(0, str(moat / "reference"))
sys.dont_write_bytecode = True

import generate_test_vectors as gtv  # noqa: E402
import moat_author_key as ak  # noqa: E402


def text(data: bytes) -> str:
    return data.decode("utf-8")


def acif_vector(v: dict) -> dict:
    return {
        "id": v["id"],
        "title": v["title"],
        "files": {path: text(data) for path, data in sorted(v["files"].items())},
        "entry_file": v["entry_file"],
        "publisher_section": v["publisher_section"],
        "body_hash": v["body_hash"],
        "metadata_hash": v["metadata_hash"],
        "content_hash": v["content_hash"],
        "payload": text(v["payload"]),
        "payload_sha256": v["payload_sha256"],
    }


def author_key_vector(v: dict) -> dict:
    out = {
        "id": v["id"],
        "kind": v["kind"],
        "title": v["title"],
        "signer": v["signer"],
        "message": text(v["message"]),
        "signature": v["signature"],
        "expected": v["expected"],
    }
    if v["kind"] == "item":
        out["list"] = v["list"]
        out["content_hash"] = v["content_hash"]
    else:
        out["source_uri"] = v["source_uri"]
        out["previous_list"] = v["previous_list"]
        out["new_list"] = v["new_list"]
    return out


def attestation_payload_vector() -> dict:
    spec = (moat / "moat-spec.md").read_text(encoding="utf-8")
    section = spec[spec.index("### Attestation Payload"):]

    def row(label: str) -> str:
        match = re.search(rf"^\| {re.escape(label)} \| `([^`]+)` \|$", section, re.MULTILINE)
        if not match:
            sys.exit(f"moat-spec.md: Attestation Payload row {label!r} not found")
        return match.group(1)

    vector = {
        "content_hash": row("Input hash"),
        "payload": row("Payload bytes"),
        "payload_sha256": row("SHA-256 of payload"),
    }
    payload = gtv.canonical_payload(vector["content_hash"])
    if text(payload) != vector["payload"] or hashlib.sha256(payload).hexdigest() != vector["payload_sha256"]:
        sys.exit("moat-spec.md: Attestation Payload vector disagrees with generate_test_vectors")
    return vector


def main() -> None:
    commit = subprocess.run(["git", "-C", str(moat), "rev-parse", "HEAD"],
                            capture_output=True, text=True, check=True).stdout.strip()
    fixtures = gtv.author_key_fixtures()
    doc = {
        "about": "MOAT test vectors for the moat crate. Generated by scripts/moat-vectors.py "
                 "from OpenScribbler/moat reference/generate_test_vectors.py; do not edit.",
        "moat_commit": commit,
        "attestation_payload": attestation_payload_vector(),
        "acif": [acif_vector(v) for v in gtv.acif_vectors()],
        "author_key": {
            "source_uri": gtv.AK_SOURCE_URI,
            "other_source_uri": gtv.AK_OTHER_SOURCE_URI,
            "keys": {
                label: {
                    "type": ak.key_type(blob),
                    "fingerprint": ak.fingerprint(blob),
                    "line": fixtures["lines"][label],
                }
                for label, blob in fixtures["keys"].items()
            },
            "lists": {
                name: {"text": text(data), "digest": ak.list_digest(data)}
                for name, data in fixtures["lists"].items()
            },
            "vectors": [author_key_vector(v) for v in gtv.author_key_vectors()],
        },
    }
    out = json.dumps(doc, indent=2, ensure_ascii=True) + "\n"
    # Binary stdout, so Windows never rewrites LF as CRLF.
    sys.stdout.buffer.write(out.encode("ascii"))


if __name__ == "__main__":
    main()
